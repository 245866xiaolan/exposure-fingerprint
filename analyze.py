#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""exposure-fingerprint -- layered triage for exposure surface.

L1 static  : banner / version / directory heuristics
L2 structural: cross-host fingerprint duplication
L3 temporal: two-sample monotonicity check
"""
import argparse
import json
import os
import socket
import time
from collections import Counter, defaultdict

TRAP_DIRS = {"/etc", "/var/spool/cron", "/etc/cron.d"}


def load(path):
    recs = []
    if not os.path.exists(path):
        return recs
    with open(path, encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            line = line.strip()
            if not line.startswith("{"):
                continue
            try:
                recs.append(json.loads(line))
            except ValueError:
                continue
    return recs


def dedup(recs):
    seen, out = set(), []
    for r in recs:
        key = (r.get("ip"), r.get("port"))
        if key in seen:
            continue
        seen.add(key)
        out.append(r)
    return out


def fingerprint(rec):
    """Stable identity used for L2 cross-host duplication."""
    svc = rec.get("svc", "")
    ev = str(rec.get("ev", ""))[:120]
    if svc == "REDIS":
        return "redis|" + ev
    if svc == "MEMCACHED":
        pid = uptime = "?"
        for chunk in ev.replace("STAT ", "").split("\n"):
            bits = chunk.split()
            if len(bits) == 2 and bits[0] == "pid":
                pid = bits[1]
            if len(bits) == 2 and bits[0] == "uptime":
                uptime = bits[1]
        return "mc|%s|%s" % (pid, uptime)
    if svc == "ES":
        return "es|" + ev
    return "%s|%s" % (svc, ev)


def l2_structural(recs):
    counts = Counter(fingerprint(r) for r in recs)
    out = []
    for r in recs:
        fp = fingerprint(r)
        row = dict(r)
        row["_fp"] = fp
        row["_dup"] = counts[fp]
        if counts[fp] > 1 and r.get("svc") in ("MEMCACHED", "ES"):
            row["verdict"] = "DECOY"
            row["why"] = "cross-host fingerprint x%d" % counts[fp]
        elif counts[fp] > 1:
            row["verdict"] = "REVIEW"
            row["why"] = "shared fingerprint x%d" % counts[fp]
        out.append(row)
    return out


def l1_static(row):
    if row.get("verdict"):
        return row
    ev = str(row.get("ev", "")).strip()
    if ev.rstrip("/") in TRAP_DIRS:
        row["verdict"] = "DECOY"
        row["why"] = "trap directory %s" % ev
    elif row.get("svc") == "MEMCACHED":
        row["verdict"] = "REVIEW"
        row["why"] = "needs temporal sample"
    else:
        row["verdict"] = "REAL"
        row["why"] = "no decoy signal in L1/L2"
    return row


def temporal_check(host, port, svc, interval):
    """Return (ok, detail). ok=False means frozen -> decoy."""
    try:
        s = socket.create_connection((host, int(port)), timeout=5)
        s.settimeout(5)
        if svc == "MEMCACHED":
            s.sendall(b"stats\r\n")
            first = s.recv(3000).decode("utf-8", "replace")
            time.sleep(interval)
            s.sendall(b"stats\r\n")
            second = s.recv(3000).decode("utf-8", "replace")
            s.close()
            a = _stat(first, "uptime")
            b = _stat(second, "uptime")
        elif svc == "REDIS":
            first = _redis_info(s)
            time.sleep(interval)
            second = _redis_info(s)
            s.close()
            a = _field(first, "uptime_in_seconds")
            b = _field(second, "uptime_in_seconds")
        else:
            s.close()
            return True, "skipped"
        if a is None or b is None:
            return True, "no-counter"
        return (b > a), "%s -> %s" % (a, b)
    except Exception as exc:
        return True, "err:%s" % str(exc)[:30]


def _redis_info(sock):
    sock.sendall(b"*2\r\n$4\r\nINFO\r\n$6\r\nserver\r\n")
    return sock.recv(4000).decode("utf-8", "replace")


def _field(text, name):
    for line in text.split("\r\n"):
        if line.startswith(name + ":"):
            try:
                return int(line.split(":", 1)[1])
            except ValueError:
                return None
    return None


def _stat(text, name):
    for line in text.split("\r\n"):
        bits = line.split()
        if len(bits) == 3 and bits[0] == "STAT" and bits[1] == name:
            try:
                return int(bits[2])
            except ValueError:
                return None
    return None


def emit_rules(rows, path="rules/generated.yaml"):
    family = defaultdict(list)
    for r in rows:
        if r.get("verdict") == "DECOY":
            fam = r["why"].split()[0]
            family[fam].append(r.get("svc"))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# generated by analyze.py --emit-rules\n")
        fh.write("version: 1\nrules:\n")
        for fam, svcs in family.items():
            uniq = sorted(set(s for s in svcs if s))
            fh.write("  - id: %s\n    services: %s\n    action: DECOY\n"
                     % (fam, json.dumps(uniq)))
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("path")
    ap.add_argument("--temporal", action="store_true")
    ap.add_argument("--interval", type=int, default=45)
    ap.add_argument("--emit-rules", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    recs = dedup(load(args.path))
    rows = [l1_static(r) for r in l2_structural(recs)]

    if args.temporal:
        for r in rows:
            if r.get("verdict") == "REVIEW":
                ok, detail = temporal_check(r["ip"], r["port"], r.get("svc", ""), args.interval)
                r["verdict"] = "REAL" if ok else "DECOY"
                r["why"] = "temporal " + detail

    if args.emit_rules:
        print("rules written to", emit_rules(rows))
        return

    if args.json:
        for r in rows:
            print(json.dumps({k: r[k] for k in ("ip", "port", "svc", "verdict", "why")},
                             ensure_ascii=False))
        return

    tally = Counter(r["verdict"] for r in rows)
    print("records %d | real %d | decoy %d | review %d" % (
        len(rows), tally["REAL"], tally["DECOY"], tally["REVIEW"]))
    print()
    print("%-18s%-7s%-12s%-9s%s" % ("IP", "PORT", "SERVICE", "VERDICT", "WHY"))
    for r in sorted(rows, key=lambda x: (x["verdict"], x.get("svc", ""))):
        print("%-18s%-7s%-12s%-9s%s" % (r["ip"], r["port"], r.get("svc", ""),
                                        r["verdict"], r["why"][:44]))


if __name__ == "__main__":
    main()
